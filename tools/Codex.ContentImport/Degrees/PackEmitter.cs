using System.Globalization;
using System.Text;

namespace Codex.ContentImport.Degrees;

/// <summary>What one approved row did, for <c>import-report.yaml</c>: counts and ids only, never a field value.</summary>
public sealed record ReportRow(string Chapter, string Parser, string Target, int Entries, List<string> Ids, int Sidebars, int Openers, List<int> RedactionRows, int PageReferencesLeft, int ReadPastBlocks = 0);

/// <summary>
/// The fixed YAML writer for the generated pack and the only code that writes it. It does not use a serializer: every scalar is double-quoted (or a
/// literal block for text with line breaks), keys are in a fixed order, lists are sorted by id and nothing depends on the machine, the date or the culture.
/// The same input gives the same bytes, so <c>--check</c> can regenerate and compare, and a hand edit shows up as a difference.
/// </summary>
public static class PackEmitter
{
    public const string ReportFile = "import-report.yaml";
    public const string ManifestFile = "manifest.yaml";

    private const string Banner = "# Generated by the local book importer. Do not edit by hand: the importer's --check fails on any difference.";

    /// <summary>The pack's generated files, by relative path (forward slashes) and content. The manifest is not among them: it is written by hand.</summary>
    public static SortedDictionary<string, string> Files(IEnumerable<FinalEntry> entries, IEnumerable<ReportRow> report)
    {
        var files = new SortedDictionary<string, string>(StringComparer.Ordinal);
        foreach (var group in entries.GroupBy(e => e.Folder, StringComparer.Ordinal))
        {
            var sb = new StringBuilder(Banner).Append('\n');
            foreach (var e in group.OrderBy(e => e.Id, StringComparer.Ordinal))
            {
                sb.Append("- id: ").Append(Scalar(e.Id, 4)).Append('\n');
                sb.Append("  name: ").Append(Scalar(e.Name, 4)).Append('\n');
                sb.Append("  source: ").Append(Scalar(e.Source, 4)).Append('\n');
                if (e.Tags.Count > 0)
                {
                    sb.Append("  tags: [").Append(string.Join(", ", e.Tags.Select(t => Scalar(t, 4)))).Append("]\n");
                }

                if (e.Description.Length > 0)
                {
                    sb.Append("  description: ").Append(Scalar(e.Description, 4)).Append('\n');
                }

                var properties = new StringBuilder();
                if (e.Category != null)
                {
                    properties.Append("    category: ").Append(Scalar(e.Category, 6)).Append('\n');
                }

                // A type's own fields, in the system's order: level, actions, traits, then the extracted labelled fields (their keys are the type's).
                // A spell's header word is its kind and its number a rank; every other type with a header number calls it a level.
                if (e.Type == "spell" && e.Kind != null)
                {
                    properties.Append("    kind: ").Append(Scalar(e.Kind, 6)).Append('\n');
                }

                if (e.Level != null)
                {
                    properties.Append(e.Type == "spell" ? "    rank: " : "    level: ").Append(e.Level.Value.ToString(CultureInfo.InvariantCulture)).Append('\n');
                }

                if (e.Actions != null)
                {
                    // The system's dropdown names the costs in words (a bare 1 would be read back as a number).
                    var cost = e.Actions switch { "1" => "one", "2" => "two", "3" => "three", var other => other };
                    properties.Append("    actions: ").Append(Scalar(cost, 6)).Append('\n');
                }

                if (e.Traits.Count > 0)
                {
                    properties.Append("    traits: [").Append(string.Join(", ", e.Traits.Select(t => Scalar(t, 6)))).Append("]\n");
                }

                if (e.Traditions.Count > 0)
                {
                    properties.Append("    traditions: [").Append(string.Join(", ", e.Traditions.Select(t => Scalar(t, 6)))).Append("]\n");
                }

                // An action's skill and least proficiency come after its traits, and before its labelled lines.
                if (e.Skill != null)
                {
                    properties.Append("    skill: ").Append(Scalar(e.Skill, 6)).Append('\n');
                }

                if (e.Proficiency != null)
                {
                    properties.Append("    proficiency: ").Append(Scalar(e.Proficiency, 6)).Append('\n');
                }

                foreach (var x in e.Extracted)
                {
                    properties.Append("    ").Append(x.Label).Append(": ").Append(Scalar(x.Text, 6)).Append('\n');
                }

                // An item's statistics from a table: the value is already the YAML the field takes (a bare number, a quoted string, a flow map).
                foreach (var x in e.Raw)
                {
                    // A value that starts on a new line is a block (a class's table of rows): its lines are already indented.
                    properties.Append("    ").Append(x.Label).Append(':').Append(x.Text.StartsWith('\n') ? x.Text : " " + x.Text).Append('\n');
                }

                // A class's or a subclass's feature rows: a name, the level it applies from, its text and the grants it makes to the sheet's ranked lists.
                if (e.Features.Count > 0)
                {
                    properties.Append("    features:\n");
                    foreach (var f in e.Features)
                    {
                        properties.Append("      - name: ").Append(Scalar(f.Name, 10)).Append('\n');
                        properties.Append("        level: ").Append(f.Level.ToString(CultureInfo.InvariantCulture)).Append('\n');
                        properties.Append("        description: ").Append(Scalar(f.Description, 10)).Append('\n');
                        if (f.Adds.Count > 0)
                        {
                            properties.Append("        adds: [").Append(string.Join(", ", f.Adds)).Append("]\n");
                        }
                    }
                }

                if (properties.Length > 0)
                {
                    sb.Append("  properties:\n").Append(properties);
                }
            }

            files[$"{group.Key}/{group.Key}.yaml"] = sb.ToString();
        }

        files[ReportFile] = Report(report);
        return files;
    }

    /// <summary>
    /// The committed rules pack of the Four Degrees system, found by walking up from the program's folder and from the working folder to a <c>content/systems/four-degrees/packs/rules-core</c> folder;
    /// null when there is none. It is the one source of stable ids (<see cref="ShippedIds"/>) whether or not a run names a pack folder.
    /// </summary>
    public static string? CommittedPackDir()
    {
        foreach (var start in new[] { AppContext.BaseDirectory, Directory.GetCurrentDirectory() })
        {
            for (var dir = new DirectoryInfo(start); dir != null; dir = dir.Parent)
            {
                var candidate = Path.Combine(dir.FullName, "content", "systems", "four-degrees", "packs", "rules-core");
                if (Directory.Exists(candidate))
                {
                    return candidate;
                }
            }
        }

        return null;
    }

    /// <summary>The ids already in a pack folder, each with the folder of its file (<c>&lt;folder&gt;/&lt;folder&gt;.yaml</c>). Nothing else of the files is read.</summary>
    public static Dictionary<string, string> ShippedIds(string packDir)
    {
        var result = new Dictionary<string, string>(StringComparer.Ordinal);
        if (!Directory.Exists(packDir))
        {
            return result;
        }

        foreach (var dir in Directory.GetDirectories(packDir))
        {
            var folder = Path.GetFileName(dir);
            var file = Path.Combine(dir, folder + ".yaml");
            if (!File.Exists(file))
            {
                continue;
            }

            foreach (var line in File.ReadLines(file))
            {
                if (line.StartsWith("- id: \"", StringComparison.Ordinal) && line.EndsWith('"'))
                {
                    result[line[7..^1]] = folder;
                }
            }
        }

        return result;
    }

    private static readonly System.Text.RegularExpressions.Regex HomebrewId = new(@"^\s*-\s+(?:\{\s*)?id:\s*[""']?([A-Za-z0-9][A-Za-z0-9_-]*)", System.Text.RegularExpressions.RegexOptions.CultureInvariant);

    /// <summary>
    /// The ids of the sibling <c>homebrew-core</c> pack (the folder beside the pack folder): every list item of a yaml file there that opens with an id, in the three forms the files use
    /// (<c>- id: x</c>, <c>- id: "x"</c> and <c>- { id: x, ... }</c>). More than the pack's entries may match (a nested list item), which only makes the clash check stricter.
    /// </summary>
    public static HashSet<string> HomebrewIds(string packDir)
    {
        var ids = new HashSet<string>(StringComparer.Ordinal);
        var home = Path.Combine(Path.GetFullPath(packDir), "..", "homebrew-core");
        if (!Directory.Exists(home))
        {
            return ids;
        }

        foreach (var file in Directory.EnumerateFiles(home, "*.yaml", SearchOption.AllDirectories))
        {
            foreach (var line in File.ReadLines(file))
            {
                var m = HomebrewId.Match(line);
                if (m.Success)
                {
                    ids.Add(m.Groups[1].Value);
                }
            }
        }

        return ids;
    }

    /// <summary>The ids of the entries that equal an id of the homebrew pack, in any type: the run fails on any (the homebrew ids are invented, and an id may not repeat across types).</summary>
    public static List<string> HomebrewClashes(IEnumerable<FinalEntry> entries, string packDir)
    {
        var homebrew = HomebrewIds(packDir);
        return entries.Select(e => e.Id).Where(homebrew.Contains).Distinct(StringComparer.Ordinal).OrderBy(i => i, StringComparer.Ordinal).ToList();
    }

    private static string Report(IEnumerable<ReportRow> rows)
    {
        var sb = new StringBuilder(Banner).Append('\n');
        sb.Append("# Counts and ids only. A redaction row is named by its number in the redaction table.\n");
        sb.Append("# A row that writes several types (an actions row also writes rules, an ancestries row also writes heritages and feats) lists the redaction rows of all its types on its first line, the row's own target.\n");
        foreach (var r in rows.OrderBy(r => r.Chapter, StringComparer.Ordinal).ThenBy(r => r.Parser, StringComparer.Ordinal).ThenBy(r => r.Target, StringComparer.Ordinal))
        {
            sb.Append("- chapter: ").Append(Scalar(r.Chapter, 4)).Append('\n');
            sb.Append("  parser: ").Append(Scalar(r.Parser, 4)).Append('\n');
            sb.Append("  target: ").Append(Scalar(r.Target, 4)).Append('\n');
            sb.Append("  entries: ").Append(r.Entries.ToString(CultureInfo.InvariantCulture)).Append('\n');
            sb.Append("  droppedSidebarBlocks: ").Append(r.Sidebars.ToString(CultureInfo.InvariantCulture)).Append('\n');
            sb.Append("  droppedOpenerBlocks: ").Append(r.Openers.ToString(CultureInfo.InvariantCulture)).Append('\n');
            sb.Append("  pageReferencesLeft: ").Append(r.PageReferencesLeft.ToString(CultureInfo.InvariantCulture)).Append('\n');
            if (r.ReadPastBlocks > 0)
            {
                // Blocks of a taken section that the row reads past (overview tables, boxes of examples): counted here, since they are in no entry.
                sb.Append("  readPastBlocks: ").Append(r.ReadPastBlocks.ToString(CultureInfo.InvariantCulture)).Append('\n');
            }

            sb.Append("  redactionRows: [").Append(string.Join(", ", r.RedactionRows.OrderBy(n => n).Select(n => n.ToString(CultureInfo.InvariantCulture)))).Append("]\n");
            sb.Append("  ids:\n");
            foreach (var id in r.Ids.OrderBy(i => i, StringComparer.Ordinal))
            {
                sb.Append("    - ").Append(Scalar(id, 6)).Append('\n');
            }
        }

        return sb.ToString();
    }

    /// <summary>A double-quoted scalar, or a literal block when the text has line breaks and survives one. <paramref name="indent"/> is where a block's lines sit.</summary>
    public static string Scalar(string value, int indent)
    {
        if (value.Contains('\n') && CanBeLiteral(value))
        {
            var pad = new string(' ', indent);
            return "|-\n" + string.Join('\n', value.Split('\n').Select(l => pad + l));
        }

        var sb = new StringBuilder("\"");
        foreach (var c in value)
        {
            switch (c)
            {
                case '\\':
                    sb.Append("\\\\");
                    break;
                case '"':
                    sb.Append("\\\"");
                    break;
                case '\n':
                    sb.Append("\\n");
                    break;
                default:
                    if (char.IsControl(c) || char.GetUnicodeCategory(c) is UnicodeCategory.Format or UnicodeCategory.LineSeparator or UnicodeCategory.ParagraphSeparator)
                    {
                        sb.Append("\\u").Append(((int)c).ToString("X4", CultureInfo.InvariantCulture));
                    }
                    else
                    {
                        sb.Append(c);
                    }

                    break;
            }
        }

        return sb.Append('"').ToString();
    }

    private static bool CanBeLiteral(string value) =>
        value.Split('\n').All(l => l.Length > 0 && l[0] != ' ' && l[^1] != ' ' && !l.Any(c => char.IsControl(c) || char.GetUnicodeCategory(c) is UnicodeCategory.Format or UnicodeCategory.LineSeparator or UnicodeCategory.ParagraphSeparator));

    /// <summary>
    /// Replaces the generated content of <paramref name="dir"/> with <paramref name="files"/>: every sub-folder and every file at the top except
    /// <c>manifest.yaml</c> is deleted first, so a chapter that is no longer approved leaves nothing behind. A folder that already holds other files and no
    /// manifest is refused.
    /// </summary>
    public static void Write(string dir, IReadOnlyDictionary<string, string> files)
    {
        var full = Path.GetFullPath(dir);
        EnsureOwnPack(full);
        WriteFiles(full, files);
    }

    /// <summary>
    /// The importer wipes what it writes, so it writes only its own packs: the folder must be <c>four-degrees/packs/&lt;name&gt;</c> with a name in
    /// <see cref="OwnPacks"/>, and a manifest there, if any, must carry that name's pack id. A hand-written pack (the homebrew one) or another system's pack
    /// is refused before anything is deleted. A folder that holds other files and no manifest is refused too.
    /// </summary>
    public static void EnsureOwnPack(string full)
    {
        if (PathGuard.FindGitRoot(full) is { } root && string.Equals(PathGuard.Resolve(full), root, StringComparison.Ordinal))
        {
            throw new DegreesException("--out names the root of a git work tree; it must name a pack folder.");
        }

        var parts = full.Split(Path.DirectorySeparatorChar, StringSplitOptions.RemoveEmptyEntries);
        if (parts.Length < 3 || parts[^3] != "four-degrees" || parts[^2] != "packs" || !OwnPacks.TryGetValue(parts[^1], out var id))
        {
            throw new DegreesException($"--out must be four-degrees/packs/<pack> with the pack one of: {string.Join(", ", OwnPacks.Keys)}.");
        }

        if (!Directory.Exists(full))
        {
            return;
        }

        var manifest = Path.Combine(full, ManifestFile);
        if (!File.Exists(manifest))
        {
            if (Directory.EnumerateFileSystemEntries(full).Any())
            {
                throw new DegreesException("--out is a folder with files in it and no manifest.yaml; it is not a pack, so it is not wiped.");
            }

            return;
        }

        var declared = File.ReadLines(manifest).Select(l => System.Text.RegularExpressions.Regex.Match(l, @"^id:\s*(\S+)\s*$")).FirstOrDefault(m => m.Success)?.Groups[1].Value.Trim('"', '\'');
        if (declared != id)
        {
            throw new DegreesException("--out: the folder's manifest does not carry this importer pack's id, so it is not wiped.");
        }
    }

    /// <summary>The importer's own pack folders and the pack id each one's manifest must carry (section 1 of the design).</summary>
    public static readonly IReadOnlyDictionary<string, string> OwnPacks = new Dictionary<string, string>(StringComparer.Ordinal)
    {
        ["rules-core"] = "four-degrees-rules",
        ["rules-creatures"] = "four-degrees-creatures",
    };

    private static void WriteFiles(string full, IReadOnlyDictionary<string, string> files)
    {
        if (Directory.Exists(full))
        {
            foreach (var sub in Directory.GetDirectories(full))
            {
                Directory.Delete(sub, recursive: true);
            }

            foreach (var file in Directory.GetFiles(full).Where(f => Path.GetFileName(f) != ManifestFile))
            {
                File.Delete(file);
            }
        }

        Directory.CreateDirectory(full);
        foreach (var (rel, text) in files)
        {
            var path = Path.Combine(full, rel.Replace('/', Path.DirectorySeparatorChar));
            Directory.CreateDirectory(Path.GetDirectoryName(path)!);
            File.WriteAllText(path, text, new UTF8Encoding(false));
        }
    }

    /// <summary>The files under <paramref name="dir"/> other than the manifest, by relative path with forward slashes.</summary>
    public static SortedDictionary<string, byte[]> Read(string dir)
    {
        var result = new SortedDictionary<string, byte[]>(StringComparer.Ordinal);
        var full = Path.GetFullPath(dir);
        if (!Directory.Exists(full))
        {
            return result;
        }

        foreach (var file in Directory.EnumerateFiles(full, "*", SearchOption.AllDirectories))
        {
            var rel = Path.GetRelativePath(full, file).Replace(Path.DirectorySeparatorChar, '/');
            if (rel != ManifestFile)
            {
                result[rel] = File.ReadAllBytes(file);
            }
        }

        return result;
    }

    /// <summary>Regenerates <paramref name="files"/> into a temp folder and compares it with <paramref name="dir"/> byte by byte. Returns the differences by path, empty when the pack is exactly what the importer writes.</summary>
    public static List<string> Check(string dir, IReadOnlyDictionary<string, string> files)
    {
        var temp = Path.Combine(Path.GetTempPath(), "codex-degrees-check-" + Guid.NewGuid().ToString("N"));
        try
        {
            WriteFiles(temp, files);
            var fresh = Read(temp);
            var actual = Read(dir);
            var differences = new List<string>();
            foreach (var path in fresh.Keys.Union(actual.Keys, StringComparer.Ordinal).OrderBy(p => p, StringComparer.Ordinal))
            {
                if (!actual.TryGetValue(path, out var have))
                {
                    differences.Add($"missing: {path}");
                }
                else if (!fresh.TryGetValue(path, out var want))
                {
                    differences.Add($"not generated: {path}");
                }
                else if (!want.AsSpan().SequenceEqual(have))
                {
                    differences.Add($"differs: {path}");
                }
            }

            return differences;
        }
        finally
        {
            if (Directory.Exists(temp))
            {
                Directory.Delete(temp, recursive: true);
            }
        }
    }
}
