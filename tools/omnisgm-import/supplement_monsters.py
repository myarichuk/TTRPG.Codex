TRAITS = {  # id -> (trait heading to insert after, name, text)
    "green-hag": ("Амфибия", "Магия ковена", COVEN.format(dc=11)),
    "night-hag": (None, "Магия ковена", COVEN.format(dc=14)),
    "sea-hag": ("Амфибия", "Магия ковена", COVEN.format(dc=11)),
}


def main():
    path = sys.argv[1].rstrip("/") + "/monster/monsters.yaml"
    text = open(path, encoding="utf-8").read()
    changed = 0
    for sid in sorted(set(REACTIONS) | set(TRAITS)):
        m = re.search(rf"(?:# source:[^\n]*\n)?- id: {re.escape(sid)}\n.*?(?=\n# source|\n- id: |\Z)", text, re.S)
        block = m.group(0)
        lines = block.split("\n")
        # the description is indented by four spaces; properties start at "  properties:"
        end = next((i for i, l in enumerate(lines) if l.startswith("  properties:")), len(lines))
        body = lines[:end]
        rest = lines[end:]
        add = []
        if sid in REACTIONS:
            name, row = REACTIONS[sid]
            if f"**_{name}._**" in "\n".join(body):
                continue
            row_lines = [f"    **_{name}._** {row}"]
            idx = next((i for i, l in enumerate(body) if l.strip() == "#### Легендарные действия"), len(body))
            while idx > 0 and idx == len(body) and body[idx - 1].strip() == "":
                idx -= 1
            new = (["    #### Реакции", ""] if not any(l.strip() == "#### Реакции" for l in body) else []) + row_lines
            if idx == len(body):
                body = body[:idx] + [""] + new
            else:
                body = body[:idx] + new + [""] + body[idx:]
        if sid in TRAITS:
            after, name, row = TRAITS[sid]
            if f"**_{name}._**" in "\n".join(body):
                continue
            actions = next(i for i, l in enumerate(body) if l.strip() == "#### Действия")
            while body[actions - 1].strip() == "":
                actions -= 1
            body = body[:actions] + ["", f"    **_{name}._** {row}"] + body[actions:]
        block2 = "\n".join(body + rest)
        # say in the source comment that rows were added
        if "# source:" in block2 and "rows added" not in block2:
            block2 = re.sub(r"(# source:[^\n]*)", r"\1; rows OmnisGM lacks (Reactions or Coven Magic) added by us from the English text", block2, count=1)
        text = text.replace(block, block2)
        changed += 1
    open(path, "w", encoding="utf-8").write(text)
    print(f"{changed} creatures supplemented")


main()
