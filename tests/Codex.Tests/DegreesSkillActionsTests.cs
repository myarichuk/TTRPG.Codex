    private static BlocksResult SplitSidebarPage(params string[] titles)
    {
        using var doc = PdfDocument.Open(SidebarPage());
        var layout = LayoutStage.Run(doc, FontRoles.Parse(Roles));
        return BlocksStage.Run(layout.Pages, new BlocksOptions
        {
            SidebarPages = new HashSet<int> { 1 },
            SidebarStarts = new Dictionary<int, int> { [1] = titles.Length },
            SidebarTitles = new Dictionary<int, IReadOnlyList<string>> { [1] = titles },
        });
    }

    [Fact]
