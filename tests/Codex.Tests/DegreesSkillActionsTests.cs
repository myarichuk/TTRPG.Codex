    private static (BlocksResult Blocks, List<SpineNode> Spine, List<TakeRow> Rows) Prepare(byte[] pdf, List<SpineNode> spine, TakeList take)
    {
        using var doc = PdfDocument.Open(pdf);
        var layout = LayoutStage.Run(doc, FontRoles.Parse(Roles));
        Assert.Empty(layout.Unclassified);
        return (BlocksStage.Run(layout.Pages, ImportPipeline.OptionsFor(spine, take.Rows)), spine, take.Rows);
    }

    private static PipelineOutput Run(TakeList? take = null, byte[]? pdf = null)
    {
        var (blocks, spine, rows) = Prepare(pdf ?? Book(), Spine(), take ?? Take());
        return ImportPipeline.Run(blocks, spine, rows, RedactionTable.Parse(NoRedactions), "pc");
    }

